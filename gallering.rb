# =============================================================================
# Image Gallery Application
# =============================================================================
# A desktop image gallery built with the Wx (wxWidgets) Ruby bindings.
# It displays JPEG images in a paginated grid, allows tagging, searching by
# tag, and viewing images in a full-screen overlay.
#
# Wx basics for the uninitiated:
#   - Wx::App        : the application object; you subclass it and implement
#                      `on_init` which Wx calls once the event loop is ready.
#   - Wx::Frame      : a top-level window (what the OS calls a "window").
#   - Wx::Panel      : a container widget that lives inside a Frame (or another
#                      Panel).  Most child widgets are parented to a Panel so
#                      that tab-navigation and background painting work right.
#   - Sizers         : layout managers.  Instead of setting pixel coordinates
#                      you add children to a Sizer and it arranges them.
#                      * BoxSizer  – lays children in a single row or column.
#                      * GridSizer – lays children in a uniform rows×cols grid.
#   - client_data    : every Wx widget can carry an arbitrary Ruby object via
#                      set_client_data / get_client_data.  It's used here as a
#                      poor-man's closure to remember "which page number does
#                      this label represent?" etc.
#   - evt_*          : event-binding helpers generated by the Wx Ruby bindings.
#                      e.g. `evt_button(widget, :handler)` means "when *widget*
#                      is clicked, call the method :handler on self".
# =============================================================================

require 'wx'         # The Wx (wxWidgets) GUI toolkit bindings for Ruby.
require 'fastimage'  # A lightweight gem used solely to read EXIF orientation
                     # from JPEG files without loading the whole image.

class ImageGalleryApp < Wx::App

  # How many thumbnail images to show on a single "page" of the grid.
  MAX_PER_PAGE = 12

  # Maximum number of numbered page-links to render in the pagination bar
  # on wide screens (e.g. "1 2 3 … 20").  The "<<", "<", ">", ">>" nav links
  # are *in addition* to this count.  On narrower windows this cap is reduced
  # dynamically so the pagination bar never overflows the window width.
  NUM_PAGINATION_LINKS = 20

  # Default window dimensions on launch.  Widths at or above DEFAULT_FRAME_WIDTH
  # keep the pagination and search controls on a single horizontal row.
  DEFAULT_FRAME_WIDTH  = 1024
  DEFAULT_FRAME_HEIGHT = 768

  # Minimum window dimensions (small mobile screen size) to guarantee that
  # controls and all 12 thumbnails always have room to render without overlap.
  MIN_FRAME_WIDTH  = 360
  MIN_FRAME_HEIGHT = 640

  # Minimum dimension floor for the thumbnail grid panel so the sizer allows
  # it to shrink freely when the window is reduced in size.
  MIN_PANEL_DIM = 100

  # Search bar sizing constants (in pixels).
  SEARCH_INPUT_DEFAULT_WIDTH = 200
  SEARCH_INPUT_MAX_WIDTH     = 300
  SEARCH_BAR_EXTRA_WIDTH     = 180

  # Pagination bar sizing constants (in pixels).
  NAV_ARROWS_RESERVED_WIDTH = 120
  COMPACT_PAGINATION_WIDTH  = 500

  # Grid spacing constants (in pixels) used by both the GridSizer and the
  # responsive cell-size calculator.
  GRID_HGAP   = 5
  GRID_VGAP   = 5
  ITEM_BORDER = 4

  # Maximum dimension cached in memory for each thumbnail on the current page.
  # Caching an 800px master image avoids re-reading JPEGs from disk during
  # interactive window resizing while keeping scaling fast and sharp.
  CACHE_MAX_DIM = 800

  # ---------------------------------------------------------------------------
  # on_init – called once by the Wx event loop after the App object is created.
  # This is where all top-level UI construction happens.
  # ---------------------------------------------------------------------------
  def on_init
    # --- Top-level frame (the OS window) ---
    # `nil` parent means this is a root window.
    @frame = Wx::Frame.new(nil, title: 'Image Gallery', size: [DEFAULT_FRAME_WIDTH, DEFAULT_FRAME_HEIGHT])

    # Enforce a minimum window size (equivalent to a small mobile viewport)
    # with no maximum size cap, allowing the window to shrink or expand freely.
    @frame.set_min_size(Wx::Size.new(MIN_FRAME_WIDTH, MIN_FRAME_HEIGHT))

    # Cache structures for responsive resizing:
    #   @page_image_cache : { path => Wx::Image } for the current page's items
    #   @page_items       : array of item hashes for in-place resize updates
    #   @active_edit_item : the item hash currently in inline tag-edit mode (if any)
    @page_image_cache = {}
    @page_items       = []
    @active_edit_item = nil

    # The outermost sizer stacks children vertically:
    #   [ image grid panel ]          ← expands to fill all remaining vertical space
    #   [ bottom panel (page+search)] ← 1 row at default/wide sizes, 2 rows when narrow
    @main_sizer = Wx::BoxSizer.new(Wx::VERTICAL)

    # --- Image grid panel ---
    # The panel is the parent for all thumbnail buttons.  The GridSizer
    # starts with 4 columns and 3 rows, 5 px horizontal gap, 5 px vertical gap.
    # Its row/column counts are dynamically adjusted on resize.
    @panel = Wx::Panel.new(@frame)
    # Setting a small explicit min_size on @panel prevents Wx::BoxSizer from
    # refusing to shrink @panel below the previous (larger) thumbnail sizes
    # when the user resizes the window smaller.
    @panel.set_min_size(Wx::Size.new(MIN_PANEL_DIM, MIN_PANEL_DIM))
    @sizer = Wx::GridSizer.new(3, 4, GRID_VGAP, GRID_HGAP)
    @panel.set_sizer(@sizer)

    # Add the panel to the main sizer.
    #   1          → proportion: this child gets all leftover vertical space.
    #   Wx::EXPAND → stretch horizontally to fill the sizer's width.
    #   Wx::ALL, 5 → 5 px padding on all four sides.
    @main_sizer.add(@panel, 1, Wx::EXPAND | Wx::ALL, 5)

    # --- Bottom panel (Pagination + Search) ---
    # Parenting the pagination and search controls to a dedicated Wx::Panel
    # (instead of directly to @frame) ensures the OS properly erases the
    # background behind StaticText labels ("Random tag", "Untagged", page links)
    # when they move during live window resizing.
    @bottom_panel       = Wx::Panel.new(@frame)
    @bottom_panel_sizer = Wx::BoxSizer.new(Wx::VERTICAL)
    @pagination_sizer   = Wx::BoxSizer.new(Wx::HORIZONTAL)
    @search_sizer       = Wx::BoxSizer.new(Wx::HORIZONTAL)
    @bottom_sizer       = Wx::BoxSizer.new(Wx::HORIZONTAL)
    create_search_bar

    # At DEFAULT_FRAME_WIDTH (1024 px) and wider, @bottom_sizer is HORIZONTAL
    # so pagination and search sit on a single centred row.  Below
    # DEFAULT_FRAME_WIDTH, @bottom_sizer switches to VERTICAL so the two bars
    # stack cleanly on narrow windows.
    @bottom_sizer.add(@pagination_sizer, 0, Wx::ALIGN_CENTER_VERTICAL, 0)
    @bottom_sizer.add(@search_sizer, 0, Wx::ALIGN_CENTER_VERTICAL, 0)
    @bottom_bar_single_row = true

    @bottom_panel_sizer.add(@bottom_sizer, 0, Wx::ALIGN_CENTER_HORIZONTAL, 0)
    @bottom_panel.set_sizer(@bottom_panel_sizer)

    @main_sizer.add(@bottom_panel, 0, Wx::EXPAND | Wx::ALL, 5)

    # Attach the outermost sizer to the frame so Wx knows how to lay things out.
    @frame.set_sizer(@main_sizer)

    # --- Load data ---
    load_images       # Scan the filesystem for JPEGs.
    load_image_tags   # Read the tag_data.txt file (if it exists).
    @current_page = 0 # Start on the first page.

    @frame.center      # Centre the window on the primary monitor.
    @frame.show        # Make the window visible.
    @main_sizer.layout # Perform initial layout so @panel has real dimensions.

    display_page       # Render the first page of thumbnails.

    # Bind the resize handler specifically to @frame (not the global App) so
    # child widget size updates do not trigger recursive resize events.
    @frame.evt_size { |event| on_resize(event) }

    # GLOBAL left-click handler.
    #
    # NOTE / DESIGN CONCERN:
    # Binding a single `evt_left_down` on the App (self) means *every* left
    # click anywhere in the application funnels through `on_click`, which then
    # has to inspect `event.get_event_object` and branch with a big if/elsif
    # chain.  This works, but it is fragile and hard to extend.  The more
    # idiomatic Wx approach is to bind click handlers per-widget (or per-widget-
    # type) at creation time, e.g.:
    #
    #   evt_left_down(@random_tag_link) { |e| on_random_tag_click(e) }
    #
    # That way each handler only deals with one kind of click and you avoid the
    # giant dispatcher below.  The global handler also intercepts clicks on
    # Buttons (which already have their own evt_button binding), forcing the
    # `event.skip()` call in on_click to let the native button handler fire.
    evt_left_down(:on_click)
  end


  # ---------------------------------------------------------------------------
  # create_search_bar – creates the search-bar widgets inside @bottom_panel:
  #   "Random tag" link | text input | "Untagged" link
  #
  # Wx::StaticText is used here to *simulate* a hyperlink (blue + underline).
  # ---------------------------------------------------------------------------
  def create_search_bar
    hand_cursor = Wx::Cursor.new(Wx::CURSOR_HAND)

    # --- "Random tag" pseudo-link ---
    @random_tag_link = Wx::StaticText.new(@bottom_panel, label: "Random tag")
    @random_tag_link.set_foreground_colour(Wx::Colour.new("blue"))
    # get_font returns a *copy*; we call .underlined on the copy, then set it
    # back.  This is the standard Wx idiom for tweaking one font attribute.
    @random_tag_link.set_font(@random_tag_link.get_font.underlined)
    @random_tag_link.set_cursor(hand_cursor)
    @search_sizer.add(@random_tag_link, 0, Wx::ALIGN_CENTER_VERTICAL | Wx::LEFT, 10)

    # --- Search text input ---
    # Wx::TE_PROCESS_ENTER makes the control emit an EVT_TEXT_ENTER event when
    # the user presses Enter, instead of inserting a newline.
    @search_input = Wx::TextCtrl.new(
      @bottom_panel,
      size: [SEARCH_INPUT_DEFAULT_WIDTH, -1],
      style: Wx::TE_PROCESS_ENTER
    )
    @search_input.set_min_size(Wx::Size.new(SEARCH_INPUT_DEFAULT_WIDTH, -1))
    @search_input.set_max_size(Wx::Size.new(SEARCH_INPUT_MAX_WIDTH, -1))

    # When the user types a search term and presses Enter, run the search.
    evt_text_enter(@search_input) do |_evt|
      search_term = @search_input.value.strip.downcase
      perform_search(search_term)
    end
    @search_sizer.add(@search_input, 0, Wx::ALIGN_CENTER_VERTICAL | Wx::LEFT | Wx::RIGHT, 5)

    # --- "Untagged" pseudo-link ---
    @untagged_link = Wx::StaticText.new(@bottom_panel, label: "Untagged")
    @untagged_link.set_foreground_colour(Wx::Colour.new("blue"))
    @untagged_link.set_font(@untagged_link.get_font.underlined)
    @untagged_link.set_cursor(hand_cursor)
    @search_sizer.add(@untagged_link, 0, Wx::ALIGN_CENTER_VERTICAL | Wx::RIGHT, 10)
  end


  # ---------------------------------------------------------------------------
  # update_bottom_bar_orientation – switches @bottom_sizer between a single
  # horizontal row (for DEFAULT_FRAME_WIDTH and wider) and two stacked rows
  # (for narrower window widths).
  # ---------------------------------------------------------------------------
  def update_bottom_bar_orientation(single_row)
    return if @bottom_bar_single_row == single_row

    @bottom_sizer.detach(@pagination_sizer)
    @bottom_sizer.detach(@search_sizer)

    if single_row
      @bottom_sizer.set_orientation(Wx::HORIZONTAL)
      @bottom_sizer.add(@pagination_sizer, 0, Wx::ALIGN_CENTER_VERTICAL, 0)
      @bottom_sizer.add(@search_sizer, 0, Wx::ALIGN_CENTER_VERTICAL, 0)
    else
      @bottom_sizer.set_orientation(Wx::VERTICAL)
      @bottom_sizer.add(@pagination_sizer, 0, Wx::ALIGN_CENTER_HORIZONTAL | Wx::BOTTOM, 4)
      @bottom_sizer.add(@search_sizer, 0, Wx::ALIGN_CENTER_HORIZONTAL, 0)
    end

    @bottom_bar_single_row = single_row
  end

  # ---------------------------------------------------------------------------
  # calculate_grid_metrics – computes the optimal grid (cols, rows) and the
  # maximum thumbnail dimensions (max_thumb_w, max_thumb_h) for @panel's
  # current size so that:
  #   1. All MAX_PER_PAGE (12) cells fit inside @panel with zero scrollbars.
  #   2. No thumbnail, tag label, or inline edit box ever overlaps an adjacent
  #      cell, even on high-DPI displays.
  #   3. The aspect ratio of the window determines whether 4×3, 3×4, or 2×6
  #      yields the largest thumbnails.
  # ---------------------------------------------------------------------------
  def calculate_grid_metrics
    panel_size = @panel.get_client_size
    avail_w = [panel_size.width, MIN_PANEL_DIM].max
    avail_h = [panel_size.height, MIN_PANEL_DIM].max

    # Measure the actual native control heights on the current OS/DPI so that
    # neither the StaticText tag row nor the inline TextCtrl editor ever makes
    # a cell taller than its grid row allocation.
    label_h = @random_tag_link ? @random_tag_link.get_best_size.height : 20
    input_h = @search_input ? @search_input.get_best_size.height : 28
    tag_row_h = [label_h, input_h].max + 4

    # Space reserved inside each cell outside the thumbnail bitmap itself:
    #   - 2 * ITEM_BORDER for the item_sizer margin inside the grid cell
    #   - 10 px for the native Wx::Button border around the bitmap
    #   - tag_row_h vertically for the tags / "EDIT" row below the button
    horizontal_overhead = (ITEM_BORDER * 2) + 10
    vertical_overhead   = (ITEM_BORDER * 2) + 10 + tag_row_h

    # Candidate (cols, rows) pairs that multiply to MAX_PER_PAGE (12).
    candidates = [[4, 3], [3, 4], [2, 6]]

    best_layout = nil
    best_limiting_dim = -1

    candidates.each do |cols, rows|
      cell_w = (avail_w - ((cols - 1) * GRID_HGAP)) / cols
      cell_h = (avail_h - ((rows - 1) * GRID_VGAP)) / rows

      thumb_w = [cell_w - horizontal_overhead, 16].max
      thumb_h = [cell_h - vertical_overhead, 16].max

      # Pick the grid arrangement that maximizes the smaller thumbnail dimension
      # so typical aspect-ratio photos render as large as possible.
      limiting_dim = [thumb_w, thumb_h].min
      if limiting_dim > best_limiting_dim
        best_limiting_dim = limiting_dim
        best_layout = {
          cols: cols,
          rows: rows,
          cell_w: cell_w,
          cell_h: cell_h,
          max_thumb_w: thumb_w,
          max_thumb_h: thumb_h
        }
      end
    end

    best_layout
  end

  # ---------------------------------------------------------------------------
  # on_resize – handles top-level window resize events.
  #
  # Performs a single top-down layout pass and refreshes @bottom_panel and
  # @panel so Windows cleanly erases and repaints all moved StaticText controls.
  # ---------------------------------------------------------------------------
  def on_resize(event)
    event.skip # Allow Wx's default frame resize handling to proceed.
    return if @resizing
    @resizing = true

    begin
      if @full_view && @full_view_image
        render_full_view_overlay
      elsif @panel && @panel.is_shown
        # Update pagination & bottom bar layout (1 row vs 2 rows) first, then
        # run a single top-down layout on @main_sizer so @panel and
        # @bottom_panel receive their exact new sizes.
        update_pagination_sizer
        @main_sizer.layout
        @bottom_panel.refresh
        rescale_current_page_items
      end
    ensure
      @resizing = false
    end
  end

  # ---------------------------------------------------------------------------
  # load_image_tags – reads tag_data.txt and populates @image_tags.
  #
  # File format (one image per line):
  #   <filename>.jpg <tag1> <tag2> <tag3> …
  #
  # Example:
  #   photos/sunset.jpg nature orange sky
  #
  # The regex captures the filename (up to .jpg/.jpeg, case-insensitive) and
  # everything after the first whitespace as the space-separated tag list.
  # After loading, any image found on disk that has no entry in the file gets
  # an empty tag array so the rest of the code can assume every path has an
  # entry in @image_tags.
  # ---------------------------------------------------------------------------
  def load_image_tags
    @image_tags = {}
    filename = 'tag_data.txt'
    if File.exist?(filename)
      File.readlines(filename).each do |line|
        # Regex breakdown:
        #   ^           – start of line
        #   (.*?\.jpg|.*?\.jpeg) – capture group 1: filename ending in .jpg or .jpeg
        #                          (.*? is non-greedy so it stops at the first match)
        #   \s+         – one or more whitespace chars separating filename from tags
        #   (.*)        – capture group 2: the rest of the line (the tags)
        #   /i          – case-insensitive (matches .JPG, .Jpeg, etc.)
        match = line.strip.match(/^(.*?\.jpg|.*?\.jpeg)\s+(.*)/i)
        if match
          path = match[1]
          tags = match[2].split(' ')   # Split on whitespace → array of tag strings.
          @image_tags[path] = tags
        end
      end
    end

    # Ensure every discovered image has at least an empty tag list.
    # This lets the rest of the code do @image_tags[path].each without nil checks.
    @images_path.each do |path|
      @image_tags[path] = [] unless @image_tags[path]
    end
  end

  # ---------------------------------------------------------------------------
  # save_image_tags – writes the entire @image_tags hash back to tag_data.txt,
  # overwriting whatever was there before.
  #
  # Format is the same as load_image_tags expects: "<path> <tag1> <tag2> …"
  # ---------------------------------------------------------------------------
  def save_image_tags
    filename = 'tag_data.txt'
    File.open(filename, 'w') do |file|
      @image_tags.each do |path, tags|
        file.puts "#{path} #{tags.join(' ')}"
      end
    end
  end

  # ---------------------------------------------------------------------------
  # load_images – recursively globs for .jpg/.jpeg files under the current
  # working directory and stores the list in @images_path.
  #
  # File::FNM_CASEFOLD makes the glob case-insensitive so .JPG, .Jpeg, etc.
  # are all matched.
  #
  # .select { |path| File.file?(path) } filters out directories that might
  # sneak in (unlikely with the extension filter, but defensive).
  #
  # @total_pages is recalculated so the pagination bar knows how many pages
  # exist.  `.ceil` rounds up so a partial last page still counts.
  # ---------------------------------------------------------------------------
  def load_images
    @images_path = Dir.glob("**/*.{jpg,jpeg}", File::FNM_CASEFOLD).select { |path| File.file?(path) }
    @total_pages = (@images_path.size.to_f / MAX_PER_PAGE).ceil
  end

  # ---------------------------------------------------------------------------
  # apply_orientation – corrects the image rotation/mirroring based on its EXIF
  # orientation tag.
  #
  # Many cameras (especially phones) store the image data rotated and record
  # the "correct" orientation in EXIF metadata.  Wx::Image does NOT honour
  # EXIF orientation when loading, so we read it separately via FastImage and
  # rotate/flip manually.
  #
  # EXIF orientation values and their corrections:
  #   1 → Normal (no transform needed)
  #   2 → Mirrored horizontally       → flip horizontal
  #   3 → Rotated 180°                → rotate 180
  #   4 → Mirrored vertically         → flip vertical
  #   5 → Transposed (mirror + 90°)   → rotate 90° CW then flip horizontal
  #   6 → Rotated 90° CW              → rotate 90° CW
  #   7 → Transversed (mirror + 270°) → rotate 90° CCW then flip horizontal
  #   8 → Rotated 90° CCW             → rotate 90° CCW
  #
  # Wx::Image methods used:
  #   rotate90(true)   → 90° clockwise   (returns new image)
  #   rotate90(false)  → 90° counter-CW  (returns new image)
  #   rotate180        → 180°            (returns new image)
  #   mirror(true)     → flip horizontal (left ↔ right)
  #   mirror(false)    → flip vertical   (top ↔ bottom)
  # ---------------------------------------------------------------------------
  def apply_orientation(image, path)
    orientation = FastImage.new(path).orientation
    case orientation
    when 2 then image = image.mirror(true)                       # flip horizontal
    when 3 then image = image.rotate180                          # rotate 180°
    when 4 then image = image.mirror(false)                      # flip vertical
    when 5 then image = image.rotate90(true).mirror(true)        # transpose: rotate CW + flip H
    when 6 then image = image.rotate90(true)                     # rotate 90° CW
    when 7 then image = image.rotate90(false).mirror(true)       # transverse: rotate CCW + flip H
    when 8 then image = image.rotate90(false)                    # rotate 90° CCW
    end
    image
  end

  # ---------------------------------------------------------------------------
  # cached_page_image – returns an EXIF-oriented Wx::Image for `path`, loading
  # it from disk only once per page and downscaling very large originals to
  # CACHE_MAX_DIM so subsequent responsive resizes are fast.
  # ---------------------------------------------------------------------------
  def cached_page_image(path)
    return @page_image_cache[path] if @page_image_cache[path]

    image = Wx::Image.new(path, Wx::BITMAP_TYPE_ANY)
    image = apply_orientation(image, path)

    if image.get_width > CACHE_MAX_DIM || image.get_height > CACHE_MAX_DIM
      ratio = [CACHE_MAX_DIM.to_f / image.get_width, CACHE_MAX_DIM.to_f / image.get_height].min
      w = [(image.get_width * ratio).to_i, 1].max
      h = [(image.get_height * ratio).to_i, 1].max
      image = image.scale(w, h)
    end

    @page_image_cache[path] = image
  end

  # ---------------------------------------------------------------------------
  # scale_image_to_box – scales a Wx::Image to fit within max_width × max_height
  # while preserving its aspect ratio.
  # ---------------------------------------------------------------------------
  def scale_image_to_box(source_image, max_width, max_height)
    ratio = [max_width.to_f / source_image.get_width, max_height.to_f / source_image.get_height].min
    scaled_width  = [(source_image.get_width * ratio).to_i, 1].max
    scaled_height = [(source_image.get_height * ratio).to_i, 1].max
    [source_image.scale(scaled_width, scaled_height), scaled_width, scaled_height]
  end

  # ---------------------------------------------------------------------------
  # display_page – rebuilds the thumbnail grid for the current page.
  #
  # It tears down all existing children of @sizer (the GridSizer) and creates
  # new Button widgets with dynamically scaled bitmaps for each image on the
  # page.
  #
  # The early-return guard skips rebuilding if neither the page number nor the
  # image list has changed since the last render (avoids redundant work when,
  # e.g., a layout event triggers a repaint on the same page).
  # ---------------------------------------------------------------------------
  def display_page(force: false)
    # Skip rebuild if nothing has changed since the last render.
    return if !force && @current_page == @last_page && @images_path == @last_images

    update_pagination_sizer(force: true) # Rebuild the "<< 1 2 3 >>" bar for the new page count.
    @main_sizer.layout                   # Ensure @panel has up-to-date dimensions before measuring.

    metrics = calculate_grid_metrics
    @sizer.set_cols(metrics[:cols])
    @sizer.set_rows(metrics[:rows])

    # Clear active edit tracking and item list BEFORE destroying C++ widgets
    # so no Ruby reference to a deleted widget can ever be accessed.
    @active_edit_item = nil
    @page_items.clear

    # clear(true) removes all children from the sizer AND destroys the
    # underlying widgets.  Without `true` the widgets would be orphaned
    # (removed from layout but still alive → memory leak).
    @sizer.clear(true)

    # Keep only the current page's images in the memory cache.
    new_cache = {}

    # Calculate the slice of @images_path that belongs to this page.
    start_index = @current_page * MAX_PER_PAGE
    # end_index is clamped so we don't go past the last image on the final page.
    end_index = [start_index + MAX_PER_PAGE - 1, @images_path.size - 1].min

    (start_index..end_index).each do |index|
      path = @images_path[index]
      next unless path && File.exist?(path)  # Skip if the file was deleted since we scanned.

      # Load (or fetch from cache) the EXIF-oriented master thumbnail image.
      source_image = cached_page_image(path)
      new_cache[path] = source_image

      # --- Scale to fit the calculated cell thumbnail box while preserving aspect ratio ---
      scaled_image, scaled_width, scaled_height = scale_image_to_box(
        source_image,
        metrics[:max_thumb_w],
        metrics[:max_thumb_h]
      )

      # Each thumbnail is wrapped in its own vertical BoxSizer so we can stack
      # the image button on top and the tag labels / edit link below.
      item_sizer = Wx::BoxSizer.new(Wx::VERTICAL)

      # Wx::Button with a bitmap acts as a clickable thumbnail.
      # Wx::BU_EXACTFIT prevents the button from enforcing a wide OS default
      # minimum width when the thumbnail shrinks on narrow screens.
      button = Wx::Button.new(@panel, style: Wx::BU_EXACTFIT)
      button.set_bitmap(Wx::Bitmap.new(scaled_image))  # Convert Wx::Image → Wx::Bitmap for display.
      btn_size = Wx::Size.new(scaled_width + 6, scaled_height + 6)
      button.set_min_size(btn_size)
      button.set_size(btn_size)
      # Store the index into @images_path so on_button_click can find the file.
      button.set_client_data(index)
      evt_button(button, :on_button_click)  # Bind the click → full-view handler.
      item_sizer.add(button, 0, Wx::ALIGN_CENTER, 0)

      # Unified item state hash.  Both @page_items and the EDIT link's
      # client_data reference this exact same Hash instance so it never goes
      # out of sync across multiple tag edits.
      item = {
        path: path,
        button: button,
        item_sizer: item_sizer,
        tags_and_edit_sizer: nil,
        tag_labels: [],
        edit_link: nil,
        text_input: nil
      }

      # Add the row of tag labels + "EDIT" link beneath the thumbnail.
      create_tags_and_edit_sizer(item, metrics[:cell_w])

      # Add the whole item (image + tags) centred in its grid cell.
      @sizer.add(item_sizer, 0, Wx::ALIGN_CENTER | Wx::ALL, ITEM_BORDER)

      @page_items << item
    end

    @page_image_cache = new_cache

    @main_sizer.layout
    @panel.refresh
    @bottom_panel.refresh

    # Record what we just rendered so the guard at the top can skip redundant
    # rebuilds on subsequent calls with the same page and image list.
    @last_page = @current_page
    @last_images = @images_path.dup
  end

  # ---------------------------------------------------------------------------
  # rescale_current_page_items – updates grid columns/rows, rescales all
  # visible thumbnail bitmaps in-place, and adjusts tag visibility to match
  # the new cell width.  Called during interactive window resizing and after
  # inline tag edits.
  # ---------------------------------------------------------------------------
  def rescale_current_page_items
    return if @page_items.empty?

    metrics = calculate_grid_metrics
    @sizer.set_cols(metrics[:cols])
    @sizer.set_rows(metrics[:rows])

    @page_items.each do |item|
      source_image = @page_image_cache[item[:path]]
      next unless source_image

      scaled_image, scaled_width, scaled_height = scale_image_to_box(
        source_image,
        metrics[:max_thumb_w],
        metrics[:max_thumb_h]
      )

      button = item[:button]
      button.set_bitmap(Wx::Bitmap.new(scaled_image))
      btn_size = Wx::Size.new(scaled_width + 6, scaled_height + 6)
      button.set_min_size(btn_size)
      button.set_size(btn_size)

      # Ensure neither tag labels nor an active inline TextCtrl overflow the cell.
      fit_tags_to_cell_width(item, metrics[:cell_w])
    end

    # Lay out the outer grid sizer (which recursively lays out each item_sizer
    # at its newly calculated grid cell position) and repaint the panel.
    @panel.layout
    @panel.refresh
  end

  # ---------------------------------------------------------------------------
  # fit_tags_to_cell_width – prevents the horizontal tag row (or active inline
  # edit TextCtrl) beneath a thumbnail from exceeding the grid column's width.
  # Any tag labels that do not fit alongside the "EDIT" link are hidden until
  # the window is widened again.
  # ---------------------------------------------------------------------------
  def fit_tags_to_cell_width(item, cell_w)
    return unless item
    max_row_w = [cell_w - (ITEM_BORDER * 2) - 4, 40].max

    if item[:text_input]
      # An inline tag editor is currently open for this thumbnail; resize it
      # to fit inside the cell width.
      input_size = Wx::Size.new(max_row_w, -1)
      item[:text_input].set_min_size(input_size)
      item[:text_input].set_max_size(input_size)
      item[:text_input].set_size(input_size)
      return
    end

    edit_link = item[:edit_link]
    return unless edit_link

    used_w = edit_link.get_best_size.width
    item[:tag_labels].each do |tag_label|
      label_w = tag_label.get_best_size.width + 5 # 5 px right margin
      if used_w + label_w <= max_row_w
        tag_label.show
        used_w += label_w
      else
        tag_label.hide
      end
    end
  end

  # ---------------------------------------------------------------------------
  # start_tag_edit – replaces a thumbnail's tag labels + "EDIT" link with an
  # inline Wx::TextCtrl pre-filled with the image's space-separated tags.
  # ---------------------------------------------------------------------------
  def start_tag_edit(item)
    return unless item

    # If another thumbnail is already being edited, close its editor first.
    if @active_edit_item && @active_edit_item != item
      finish_tag_edit(@active_edit_item, save: false)
    end

    item_sizer = item[:item_sizer]
    tags_sizer = item[:tags_and_edit_sizer]
    path       = item[:path]

    # Clear widget references on `item` BEFORE destroying the C++ controls so
    # resize handlers can never touch a deleted StaticText object.
    item[:tags_and_edit_sizer] = nil
    item[:tag_labels]          = []
    item[:edit_link]           = nil

    if tags_sizer
      item_sizer.detach(tags_sizer)
      tags_sizer.show_items(false)
      tags_sizer.clear(true)
    end

    cell_w  = calculate_grid_metrics[:cell_w]
    input_w = [cell_w - (ITEM_BORDER * 2) - 4, 40].max

    text_input = Wx::TextCtrl.new(
      @panel,
      value: (@image_tags[path] || []).join(' '),
      size: [input_w, -1],
      style: Wx::TE_PROCESS_ENTER
    )
    text_input.set_min_size(Wx::Size.new(input_w, -1))
    text_input.set_max_size(Wx::Size.new(input_w, -1))

    item[:text_input] = text_input
    @active_edit_item = item

    # Enter → save the new tags and restore the tag labels row.
    evt_text_enter(text_input) do |_evt|
      finish_tag_edit(item, save: true)
    end

    # Escape → cancel editing and restore the previous tag labels row.
    text_input.evt_key_down do |evt|
      if evt.get_key_code == Wx::K_ESCAPE
        finish_tag_edit(item, save: false)
      else
        evt.skip
      end
    end

    item_sizer.add(text_input, 0, Wx::ALIGN_CENTER, 0)
    @panel.layout
    @panel.refresh

    text_input.set_focus
    text_input.set_selection(-1, -1)
  end

  # ---------------------------------------------------------------------------
  # finish_tag_edit – closes the inline Wx::TextCtrl editor (optionally saving
  # the modified tags to disk) and rebuilds the thumbnail's tag row.
  # ---------------------------------------------------------------------------
  def finish_tag_edit(item, save:)
    return unless item && item[:text_input]

    @active_edit_item = nil if @active_edit_item == item

    # Clear the :text_input reference BEFORE destroying the C++ control.
    text_input = item[:text_input]
    item[:text_input] = nil

    path       = item[:path]
    item_sizer = item[:item_sizer]

    if save
      new_tags = text_input.value.split(' ')
      @image_tags[path] = new_tags
      save_image_tags
    end

    item_sizer.detach(text_input)
    text_input.destroy

    create_tags_and_edit_sizer(item, calculate_grid_metrics[:cell_w])
    rescale_current_page_items
  end

  # ---------------------------------------------------------------------------
  # update_pagination_sizer – rebuilds the row of page-navigation links and
  # switches the bottom bar between 1 row (at DEFAULT_FRAME_WIDTH and above)
  # and 2 rows (below DEFAULT_FRAME_WIDTH).
  #
  # Layout:  << < [page numbers…] > >>
  #
  # Each "link" is a Wx::StaticText styled to look like a hyperlink (blue,
  # underlined).  The *current* page number is shown in the default colour
  # (black, not underlined) so the user can see where they are.
  #
  # Disabled links (e.g. "<<" when already on page 0) are shown in grey and
  # are NOT underlined.  They are still technically clickable at the widget
  # level, but the on_click handler clamps the resulting page number to valid
  # bounds so clicking a greyed-out link is a harmless no-op.
  # ---------------------------------------------------------------------------
  def update_pagination_sizer(force: false)
    outer_w  = @frame.get_size.width
    client_w = [@frame.get_client_size.width, MIN_FRAME_WIDTH].max

    # Keep pagination and search on a single row at the default window width
    # (1024 px) and larger; stack into two rows only on smaller windows.
    single_row = outer_w >= DEFAULT_FRAME_WIDTH
    update_bottom_bar_orientation(single_row)

    if single_row
      input_w = SEARCH_INPUT_DEFAULT_WIDTH
      search_bar_w = input_w + SEARCH_BAR_EXTRA_WIDTH
      avail_pagination_w = [client_w - search_bar_w, NAV_ARROWS_RESERVED_WIDTH + 90].max
      link_pad = 6
      per_link_px = 26
    else
      # On narrower screens, let the search input adapt to the narrow width.
      input_w = [client_w - SEARCH_BAR_EXTRA_WIDTH, 80].max.clamp(80, SEARCH_INPUT_MAX_WIDTH)
      avail_pagination_w = client_w
      link_pad = client_w < COMPACT_PAGINATION_WIDTH ? 5 : 8
      per_link_px = client_w < COMPACT_PAGINATION_WIDTH ? 24 : 32
    end

    if @last_search_input_w != input_w
      @search_input.set_min_size(Wx::Size.new(input_w, -1))
      @search_input.set_size(Wx::Size.new(input_w, -1))
      @last_search_input_w = input_w
    end

    max_links_for_width = [((avail_pagination_w - NAV_ARROWS_RESERVED_WIDTH) / per_link_px).floor, 3].max
    visible_links_cap = [max_links_for_width, NUM_PAGINATION_LINKS].min

    # Skip destroying and recreating the pagination StaticText widgets during
    # continuous mouse-drag resizes unless the pagination state actually changed.
    pagination_state = [@current_page, @total_pages, visible_links_cap, link_pad]
    return if !force && @last_pagination_state == pagination_state
    @last_pagination_state = pagination_state

    # Destroy all existing pagination link widgets before rebuilding.
    @pagination_sizer.clear(true)

    hand_cursor = Wx::Cursor.new(Wx::CURSOR_HAND)

    # --- "<<" (jump to first page) ---
    first_link = Wx::StaticText.new(@bottom_panel, label: "<<")
    first_link.set_foreground_colour(@current_page > 0 ? Wx::Colour.new("blue") : Wx::Colour.new("grey"))
    if @current_page > 0
      first_link.set_font(first_link.get_font.underlined)
      first_link.set_cursor(hand_cursor)
    end
    first_link.set_client_data(0)  # Clicking navigates to page 0.
    @pagination_sizer.add(first_link, 0, Wx::LEFT | Wx::RIGHT, link_pad)

    # --- "<" (previous page) ---
    prev_link = Wx::StaticText.new(@bottom_panel, label: "<")
    prev_link.set_foreground_colour(@current_page > 0 ? Wx::Colour.new("blue") : Wx::Colour.new("grey"))
    if @current_page > 0
      prev_link.set_font(prev_link.get_font.underlined)
      prev_link.set_cursor(hand_cursor)
    end
    # Store the target page.  If already on page 0 this will be -1, but the
    # click handler clamps it to valid bounds (see on_click).
    prev_link.set_client_data(@current_page - 1)
    @pagination_sizer.add(prev_link, 0, Wx::LEFT | Wx::RIGHT, link_pad)

    # --- Numbered page links ---
    # Compute the visible window of page numbers.
    #
    # Logic step by step:
    #   1. Start by centring the window on @current_page.
    #   2. Clamp so we don't go below page 0.
    #   3. Compute end_page from start_page + window size, clamped to last page.
    #   4. If the window is too small (near the end of the page list), shift
    #      start_page backwards to fill the window.
    #   5. Final guard: ensure start_page never goes below 0 (this happens when
    #      @total_pages < visible_links_cap and the backward shift overshoots).
    start_page = [@current_page - visible_links_cap / 2, 0].max
    end_page = [(start_page + visible_links_cap - 1), @total_pages - 1].min
    # If the window is shorter than desired (we're near the last page), try to
    # extend it backwards.
    end_page = @total_pages - 1 if end_page - start_page < visible_links_cap - 1
    start_page = end_page - visible_links_cap + 1 if end_page - start_page < visible_links_cap - 1 && @total_pages > visible_links_cap
    # Guard: when @total_pages < visible_links_cap the backward shift above
    # can push start_page negative.  Clamp to 0.
    start_page = [start_page, 0].max

    (start_page..end_page).each do |page_num|
      # page_num is 0-based internally; display is 1-based for the user.
      link = Wx::StaticText.new(@bottom_panel, label: (page_num + 1).to_s)
      # Highlight non-current pages as clickable-looking links with a hand cursor.
      if page_num != @current_page
        link.set_foreground_colour(Wx::Colour.new("blue"))
        link.set_font(link.get_font.underlined)
        link.set_cursor(hand_cursor)
      end
      link.set_client_data(page_num)  # The on_click handler reads this to navigate.
      @pagination_sizer.add(link, 0, Wx::LEFT | Wx::RIGHT, link_pad)
    end

    # --- ">" (next page) ---
    next_link = Wx::StaticText.new(@bottom_panel, label: ">")
    next_link.set_foreground_colour(@current_page < @total_pages - 1 ? Wx::Colour.new("blue") : Wx::Colour.new("grey"))
    if @current_page < @total_pages - 1
      next_link.set_font(next_link.get_font.underlined)
      next_link.set_cursor(hand_cursor)
    end
    next_link.set_client_data(@current_page + 1)
    @pagination_sizer.add(next_link, 0, Wx::LEFT | Wx::RIGHT, link_pad)

    # --- ">>" (jump to last page) ---
    last_link = Wx::StaticText.new(@bottom_panel, label: ">>")
    last_link.set_foreground_colour(@current_page < @total_pages - 1 ? Wx::Colour.new("blue") : Wx::Colour.new("grey"))
    if @current_page < @total_pages - 1
      last_link.set_font(last_link.get_font.underlined)
      last_link.set_cursor(hand_cursor)
    end
    last_link.set_client_data(@total_pages - 1)
    @pagination_sizer.add(last_link, 0, Wx::LEFT | Wx::RIGHT, link_pad)
  end


  # ---------------------------------------------------------------------------
  # on_click – the *global* left-mouse-down handler (bound in on_init via
  # `evt_left_down(:on_click)`).
  #
  # Because it catches ALL left clicks in the app, it acts as a dispatcher:
  # it inspects what widget was clicked and the client_data attached to it,
  # then routes to the appropriate action.
  #
  # This is the most complex method in the file.  The branching logic:
  #
  #   StaticText clicked?
  #     client_data is a Hash?
  #       :type == 'edit'       → enter inline tag-editing mode
  #       :type == 'tag_search' → search for the clicked tag
  #     client_data is an Integer?
  #       → it's a pagination link; navigate to that page (clamped to bounds)
  #     client_data is nil?
  #       → check if it's the "Random tag" or "Untagged" link by identity
  #
  #   Button clicked?
  #     → event.skip() lets the native button handler (on_button_click) fire
  #
  #   Full-view mode active?
  #     → any click dismisses the full-view overlay
  #
  #   Otherwise → event.skip() (let Wx handle it natively)
  # ---------------------------------------------------------------------------
  def on_click(event)
    clicked_object = event.get_event_object

    # If an inline tag editor is open and the user clicks outside of it, close
    # the editor before dispatching the click.
    if @active_edit_item && clicked_object != @active_edit_item[:text_input]
      finish_tag_edit(@active_edit_item, save: false)
    end

    if clicked_object.is_a?(Wx::StaticText)
      client_data = clicked_object.get_client_data

      case client_data
      when Hash
        if client_data[:type] == 'edit'
          start_tag_edit(client_data[:item])
        elsif client_data[:type] == 'tag_search'
          # A tag label under a thumbnail was clicked → search for that tag.
          on_tag_click(event)
        end

      when Integer
        # A pagination link was clicked; client_data holds the target page number.
        max_page = [@total_pages - 1, 0].max
        @current_page = client_data.clamp(0, max_page)
        display_page

      when nil
        # The "Random tag" and "Untagged" links have no client_data set,
        # so we identify them by object identity.
        if clicked_object == @random_tag_link
          on_random_tag_click(event)
        elsif clicked_object == @untagged_link
          on_untagged_click(event)
        end
      end

    elsif clicked_object.is_a?(Wx::Button)
      # A thumbnail button was clicked.  We do NOT handle it here; event.skip()
      # lets the evt_button binding (on_button_click) fire instead.
      event.skip()

    elsif @full_view
      # In full-view mode, any click on the background dismisses the overlay.
      on_full_view_click(event)

    else
      # Clicked on something we don't care about; let Wx handle it.
      event.skip()
    end
  end

  # ---------------------------------------------------------------------------
  # create_tags_and_edit_sizer – builds the horizontal row of tag labels and
  # the "EDIT" link that appears beneath each thumbnail.
  #
  # Layout:  [tag1] [tag2] [tag3] … [EDIT]
  #
  # Each tag label is a clickable Wx::StaticText (blue) that triggers a search
  # for that tag.  The "EDIT" label opens the inline text-field editor.
  #
  # Updates the passed `item` hash directly so `@page_items` and the EDIT
  # link's `client_data` always share a single source of truth.
  # ---------------------------------------------------------------------------
  def create_tags_and_edit_sizer(item, cell_w)
    path       = item[:path]
    item_sizer = item[:item_sizer]

    hand_cursor = Wx::Cursor.new(Wx::CURSOR_HAND)
    tags_and_edit_sizer = Wx::BoxSizer.new(Wx::HORIZONTAL)
    tag_labels = []

    if @image_tags[path]
      @image_tags[path].each do |tag|
        tag_label = Wx::StaticText.new(@panel, label: tag)
        tag_label.set_foreground_colour(Wx::Colour.new("blue"))
        tag_label.set_cursor(hand_cursor)
        # Attach a hash so the global on_click handler knows this is a
        # tag-search link and which tag to search for.
        tag_label.set_client_data({ type: 'tag_search', tag: tag })
        tags_and_edit_sizer.add(tag_label, 0, Wx::ALIGN_CENTER | Wx::RIGHT, 5)
        tag_labels << tag_label
      end
    end

    # The "EDIT" pseudo-link.
    edit_link = Wx::StaticText.new(@panel, label: "EDIT")
    edit_link.set_foreground_colour(Wx::Colour.new("blue"))
    edit_link.set_font(edit_link.get_font.underlined)
    edit_link.set_cursor(hand_cursor)

    item[:tags_and_edit_sizer] = tags_and_edit_sizer
    item[:tag_labels]          = tag_labels
    item[:edit_link]           = edit_link
    item[:text_input]          = nil

    edit_link.set_client_data({ type: 'edit', item: item })
    tags_and_edit_sizer.add(edit_link, 0, Wx::ALIGN_CENTER, 0)

    item_sizer.add(tags_and_edit_sizer, 0, Wx::ALIGN_CENTER, 0)

    # Hide any tag labels that would overflow the current column width.
    fit_tags_to_cell_width(item, cell_w)
  end


  # ---------------------------------------------------------------------------
  # on_button_click – handles a click on a thumbnail button.
  #
  # If we're already in full-view mode, a click dismisses it (toggle behaviour).
  # Otherwise, it:
  #   1. Hides the entire gallery UI (grid and bottom bar).
  #   2. Paints the frame background black.
  #   3. Loads the full-resolution image, applies EXIF orientation, and scales
  #      it to fit the frame while preserving aspect ratio.
  #   4. Creates a temporary Wx::Panel with a StaticBitmap (the image) and a
  #      StaticText (the file path), centred horizontally.
  #
  # Clicking anywhere while in full view calls on_full_view_click to tear down
  # the overlay and restore the gallery.
  # ---------------------------------------------------------------------------
  def on_button_click(event)
    if @active_edit_item
      finish_tag_edit(@active_edit_item, save: false)
    end

    button = event.get_event_object
    image_index = button.get_client_data   # The index we stored in display_page.
    image_path = @images_path[image_index]

    if @full_view
      # Already showing a full-size image → dismiss it.
      on_full_view_click(event)
    else
      @full_view = true
      @frame.set_background_colour(Wx::Colour.new("black"))
      @frame.refresh  # Repaint the frame background immediately.

      # Hide all gallery UI: bottom panel (pagination + search) and image grid.
      @bottom_panel.hide
      @panel.hide
      @main_sizer.layout

      # --- Load and cache the full-resolution image for responsive resizing ---
      full_image = Wx::Image.new(image_path, Wx::BITMAP_TYPE_ANY)
      @full_view_image = apply_orientation(full_image, image_path)
      @full_view_path  = image_path

      render_full_view_overlay
    end
  end

  # ---------------------------------------------------------------------------
  # render_full_view_overlay – builds or updates the full-view overlay panel
  # scaled to the frame's current client dimensions.
  # ---------------------------------------------------------------------------
  def render_full_view_overlay
    return unless @full_view && @full_view_image

    if @full_view_panel
      @full_view_panel.destroy
      @full_view_panel = nil
    end

    client_size = @frame.get_client_size
    frame_width  = [client_size.width, 50].max
    frame_height = [client_size.height, 50].max

    # Reserve ~40 px vertically for the file path caption below the image.
    max_width  = [frame_width - 10, 20].max
    max_height = [frame_height - 40, 20].max

    # Scale to fit the frame while preserving aspect ratio.
    # Use the *minimum* of the two ratios so the entire image is always
    # visible (no clipping), just like the thumbnail scaling logic.
    scaled_image, _scaled_width, _scaled_height = scale_image_to_box(@full_view_image, max_width, max_height)
    full_bitmap = Wx::Bitmap.new(scaled_image)

    # --- Build the full-view overlay panel ---
    # Wx::SIMPLE_BORDER gives the panel a thin 1-px border (mostly cosmetic).
    @full_view_panel = Wx::Panel.new(@frame, style: Wx::SIMPLE_BORDER)
    @full_view_panel.set_background_colour(Wx::Colour.new("black"))
    size = Wx::Size.new(frame_width, frame_height)
    @full_view_panel.set_size(size)

    # StaticBitmap displays a Wx::Bitmap as a non-interactive image.
    static_image = Wx::StaticBitmap.new(@full_view_panel, label: full_bitmap)

    # Show the file path below the image in white-on-black text.
    @file_path_text = Wx::StaticText.new(@full_view_panel, label: @full_view_path)
    @file_path_text.set_font(Wx::Font.new(12, Wx::FONTFAMILY_DEFAULT, Wx::FONTSTYLE_NORMAL, Wx::FONTWEIGHT_NORMAL))
    @file_path_text.set_foreground_colour(Wx::Colour.new("white"))
    @file_path_text.set_background_colour(Wx::Colour.new("black"))

    # Lay out the overlay panel: image on top, file path below, both centred.
    @full_view_panel.set_sizer(Wx::BoxSizer.new(Wx::VERTICAL))
    @full_view_panel.get_sizer.add(static_image, 1, Wx::ALIGN_CENTER | Wx::ALL, 5)
    @full_view_panel.get_sizer.add(@file_path_text, 0, Wx::ALIGN_CENTER | Wx::ALL, 5)
    # Ensure the sizer is at least as wide as the frame so centring works.
    @full_view_panel.get_sizer.set_min_size(frame_width, -1)

    @full_view_panel.show(true)
    @full_view_panel.layout

    # Position the panel at the top-left of the frame's client area.
    @full_view_panel.set_position(Wx::Point.new(0, 0))
    @frame.refresh
  end

  # ---------------------------------------------------------------------------
  # on_full_view_click – exits full-view mode.
  #
  # Destroys the overlay panel, restores the default background, and re-shows
  # the gallery UI panels that were hidden in on_button_click.
  # ---------------------------------------------------------------------------
    # ---------------------------------------------------------------------------
  # on_full_view_click – exits full-view mode.
  #
  # Destroys the overlay panel, restores the default background, and re-shows
  # the gallery UI panels that were hidden in on_button_click.
  # ---------------------------------------------------------------------------
  def on_full_view_click(event)
    @full_view = false
    @full_view_image = nil
    @full_view_path  = nil
    @frame.set_background_colour(Wx::NULL_COLOUR)
    @frame.refresh

    # Destroy the temporary overlay panel and all its children.
    if @full_view_panel
      @full_view_panel.destroy
      @full_view_panel = nil
    end

    # Re-show the grid panel and bottom bar panel.
    @panel.show
    @bottom_panel.show

    # Trigger layout recalculations and rescale thumbnails in case the window
    # was resized while full-view mode was active.
    update_pagination_sizer(force: true)
    @main_sizer.layout
    @bottom_panel.refresh
    rescale_current_page_items
  end


  # ---------------------------------------------------------------------------
  # on_tag_click – handles a click on a tag label beneath a thumbnail.
  #
  # It reads the tag string from the widget's client_data, puts it into the
  # search input field (for visual feedback), and runs a search.
  # ---------------------------------------------------------------------------
  def on_tag_click(event)
    clicked_object = event.get_event_object
    if clicked_object.is_a?(Wx::StaticText)
      client_data = clicked_object.get_client_data
      if client_data.is_a?(Hash) && client_data[:type] == 'tag_search'
        tag = client_data[:tag]
        @search_input.value = tag   # Show the tag in the search box.
        perform_search(tag)
      end
    end
  end

  # ---------------------------------------------------------------------------
  # perform_search – filters @images_path to only images whose tags match the
  # search term, then re-renders the grid from page 0.
  #
  # Search semantics:
  #   - The search term is split on whitespace into individual tokens.
  #   - ALL tokens must match (AND logic).
  #   - A token matches if ANY of the image's tags *contains* the token as a
  #     substring (case-insensitive).  So searching "sun" matches a tag "sunset".
  #   - An empty search term resets to showing ALL images.
  # ---------------------------------------------------------------------------
  def perform_search(search_term)
    if @active_edit_item
      finish_tag_edit(@active_edit_item, save: false)
    end

    if search_term.empty?
      load_images  # Reset to the full unfiltered list.
    else
      search_tags = search_term.downcase.split(' ')

      # Select only images where every search token is found in at least one tag.
      # `tags.any? { |tag| tag.downcase.include?(search_tag) }` is the
      # substring-match check for a single token against a single image's tags.
      @images_path = @image_tags.select do |_, tags|
        search_tags.all? do |search_tag|
          tags.any? { |tag| tag.downcase.include?(search_tag) }
        end
      end.keys  # .keys → we only need the file paths, not the tag arrays.

      @total_pages = (@images_path.size.to_f / MAX_PER_PAGE).ceil
    end

    @current_page = 0
    display_page
  end

  # ---------------------------------------------------------------------------
  # on_random_tag_click – picks a random tag from all images and searches for it.
  #
  # Flattening all tag arrays and calling .uniq gives us the set of distinct
  # tags across the entire collection.  .sample picks one at random.
  # If no tags exist at all, random_tag is nil and we do nothing.
  # ---------------------------------------------------------------------------
  def on_random_tag_click(event)
    all_tags = @image_tags.values.flatten.uniq
    random_tag = all_tags.sample
    if random_tag
      @search_input.value = random_tag
      perform_search(random_tag)
    end
  end

  # ---------------------------------------------------------------------------
  # on_untagged_click – filters the gallery to show only images that have no
  # tags (empty or nil tag array) and whose file still exists on disk.
  #
  # Clears the search input to indicate no text search is active.
  # ---------------------------------------------------------------------------
  def on_untagged_click(event)
    @search_input.value = ""
    @images_path = @image_tags.select { |path, tags| (tags.nil? || tags.empty?) && path && File.exist?(path) }.keys
    @total_pages = (@images_path.size.to_f / MAX_PER_PAGE).ceil
    @current_page = 0
    display_page
  end
end

